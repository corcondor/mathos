#!/usr/bin/env python3
"""v50: exact quotient map and rank-zero genus-two rational-point theorem.

Given C_T: s²=(6u²+2+3T)²+4(u²-1-T)³, put
x=u²-1-T, y=(s-6x-8-9T)/2.
Then (x,y) lies on E1_T: y²+6xy+(8+9T)y=x³.

If E1_T(Q) has rank 0 and torsion exactly Z/3 generated by (0,0),
then every finite C_T(Q) point has x=0, hence u²=1+T.
All such points are (u,s)=(±sqrt(1+T), ±(8+9T)), if sqrt rational.
For T>0, the sextic is squarefree with leading coefficient 4,
so its smooth projective model has exactly two rational infinities.

This script verifies the map and arithmetic conditions, NOT Sage's
separate proof of the first quotient's rank 0.
"""
import sympy as s
from math import isqrt, gcd

u,T,x,y=s.symbols("u T x y")
X=u*u-1-T
H=6*X+8+9*T
f=s.expand((6*u*u+2+3*T)**2+4*X**3)
assert s.expand((2*y+H)**2-f-4*(y*y+H*y-X**3))==0
assert s.Poly(f,u).degree()==6
assert s.Poly(f,u).LC()==4
disc=s.factor(s.discriminant(f,u))
assert disc==3869835264*T**4*(4*T+3)*(9*T+8)**6
assert s.factor(f.subs(u,0))==-T*T*(4*T+3)
print("PASS: C_T -> E1_T exact rational morphism, degree 2")
print("PASS: genus-two sextic discriminant and two rational points at infinity")

def first_curve_count(t,p):
    a3=8+9*t
    delta=-243*t*a3**3
    assert delta%p
    return 1+sum(
        1 for xx in range(p) for yy in range(p)
        if (yy*yy+6*xx*yy+a3*yy-xx**3)%p==0
    )

for t,checks in [(1,((5,3),(7,6))),(100003,((7,6),(13,15)))]:
    for p,num in checks:
        assert first_curve_count(t,p)==num
    assert gcd(*(num for p,num in checks))==3
    # The rational point (0,0) has exact order 3 by tangent y=0
    # (its line intersects y²+6xy+a3*y=x³ only at x=0 with mult 3).
    # Reduction therefore gives the full rational torsion group Z/3.
    z=1+t
    assert isqrt(z)**2!=z
    print("PASS: T=",t,"E1(Q)_tors=Z/3, 1+T nonsquare")
    print("CONDITIONAL ON CERTIFIED E1 RANK ZERO: C_T(Q)={infty+,infty-}")

rho=100003
bs=(1,2,3,6,9,18,27,54,81,162,243,486)
assert all(isqrt(b*b+rho)**2!=b*b+rho for b in bs)
print("PASS: rho=100003 has no boundary u²=1+rho/b² for ANY b|486")
print("Note: proving E1_{rho/b²}(Q) rank zero for b>1 needs separate Sage runs.")
